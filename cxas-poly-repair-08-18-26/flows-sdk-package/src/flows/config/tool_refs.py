"""The one walk of "which tools does this config reference?".

Every stage that needs a config's tool surface has to agree on this answer, or a
tool is generated but never shipped — or demanded at the gate but never built.
They did not agree. Five near-copies of this walk existed, and only the one in the
Studio push gate looked at ``cancel.tool`` / ``escalate.tool``, so a CUSTOM cancel
tool was never generated by codegen, never stub-checked by the pre-push gates, and
then rejected at push time for not being in the app. This module is the single
implementation the others delegate to.

It lives in `flows` rather than in `sffix` (where the widest copy was) for one
reason: `flows.deploy` needs it, and `flows` must not import `sffix` — the
dependency runs sffix -> flows and reversing it is a cycle.
`sffix.normalize.referenced_tools` re-exports this function, so the blessed public
name is unchanged and there is exactly one body behind it.

A WIDER walk than `flows.authoring.build.collect`: slot setters, task tools,
`bootstrap.tool`, `correction_tool`, `intent_change.tool`, `cancel.tool`,
`escalate.tool`, and every exhaust disposition — slot `validation`, `steer_back`,
task `on_failure`, task `awaits.on_timeout` and the flow-level `no_input` — in BOTH
legal spellings of `then` (a `{"tool": …}` dict and a bare tool-name string).
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional, Set

__all__ = ["referenced_tools", "reserved_tool_names", "RESERVED_TOOL_FALLBACK"]


# Fallback used only when the blessed manifest can't be imported. Kept in sync with
# the live manifest by `packages/sffix/tests/test_normalize_differential.py`.
RESERVED_TOOL_FALLBACK = frozenset(
    {
        "slot_filling_engine", "slot_intake", "cancel_flow", "transfer_to_human",
        "confirm_pending", "reject_pending", "set_slot_change", "classify_turn_intent",
        "try_again", "new_flow_instance", "resume_flow", "set_active_flow",
        "settle_guard",
    }
)


def reserved_tool_names() -> Set[str]:
    """The set of reserved framework tool names (from the blessed manifest)."""
    try:
        from ..engine import blessed_source as bs

        return set(bs._FRAMEWORK_TOOLS) | {"set_active_flow"}  # noqa: SLF001
    except Exception:  # noqa: BLE001 — never wedge normalization on framework infra
        return set(RESERVED_TOOL_FALLBACK)


#: `then` spellings the FRAMEWORK resolves itself, not names of app tools. The engine
#: turns a bare-string `then` into a function_call verbatim
#: (`_resolve_exhaust_action`: `"then": "escalate"` -> `{"name": "escalate", "args": {}}`),
#: so a string `then` IS a tool reference — except for these, which name the framework's
#: own dispositions. Reporting them would invent phantom tools that codegen would be
#: asked to write and the push gate would then demand. `transfer_to_human` and the rest
#: of the framework surface are already excluded by :func:`reserved_tool_names`; these
#: two are not tools in the manifest at all, so they need their own line.
_FRAMEWORK_THEN_ACTIONS = frozenset({"escalate", "end_session"})


def _then_tool(then: Any) -> Optional[str]:
    """The tool a `then` disposition names, in EITHER legal spelling.

    ``then`` is a string or a dict — the validator accepts both
    (`_check_on_exhaust`: "'then' can be a string action name or a dict with
    tool+args") and the engine resolves both. Only the dict form was walked, so a
    custom tool named the string way was invisible: never generated, never
    stub-checked, and then rejected at push time for not being in the app.
    """
    if isinstance(then, dict):
        tool = then.get("tool")
        return tool if isinstance(tool, str) and tool else None
    if isinstance(then, str) and then and then not in _FRAMEWORK_THEN_ACTIONS:
        return then
    return None


def _exhaust_then_tool(block: Any) -> Optional[str]:
    """The ``on_exhaust.then`` tool of a validation / steer_back / on_failure block."""
    if not isinstance(block, dict):
        return None
    return _then_tool((block.get("on_exhaust") or {}).get("then"))



def norm_sources(src: Any) -> List[str]:
    """A slot's `source` as a list. It is legally a bare string OR a list of them."""
    if isinstance(src, list):
        return [x for x in src if isinstance(x, str)]
    if isinstance(src, str):
        return [src]
    return []


def is_task_sourced(src: Any) -> bool:
    """True when any declared source is `task:<name>`.

    `str(["task:get_balance"])` is `"['task:get_balance']"`, which does not start with
    `task:` — so stringifying a list source silently classified a task-sourced slot as
    user-sourced. Fixed in sffix first; ported here when this became the single walk,
    because aliasing to a still-broken implementation would have reverted that fix.
    """
    return any(x.startswith("task:") for x in norm_sources(src))


def referenced_tools(config: Dict[str, Any]) -> Dict[str, Dict[str, Any]]:
    """Every tool the config names, mapped to how it is referenced.

    Keyed by tool name, excluding reserved framework/control tools. Each value
    describes the tool's role so codegen can build a focused prompt::

      {"kind": "user_setter"|"task_setter"|"task"|"bootstrap"|"correction"
               |"intent_change"|"cancel"|"escalate"|"exhaust",
       "slot": <slot dict>?, "task": <task dict>?}

    Note the walk does NOT filter ``*_dag`` names: a task whose tool is another
    flow's dag is a real reference, and only the caller knows whether that dag is
    being rendered in the same breath (the push bundle) or must already exist.
    `flows.deploy.render.missing_tools` does that filtering.
    """
    cfg = config or {}
    reserved = reserved_tool_names()
    out: Dict[str, Dict[str, Any]] = {}

    for s in cfg.get("slots", []) or []:
        if not isinstance(s, dict):
            continue
        setter = s.get("setter")
        if not setter or setter in reserved:
            continue
        if is_task_sourced(s.get("source")):
            # A task-sourced slot's "setter" is fed by the task executor's output,
            # not user input — its envelope is the task-tool shape.
            out.setdefault(setter, {"kind": "task_setter", "slot": s})
        else:
            out.setdefault(setter, {"kind": "user_setter", "slot": s})

    for t in cfg.get("tasks", []) or []:
        if not isinstance(t, dict):
            continue
        tool = t.get("tool")
        if tool and tool not in reserved:
            out.setdefault(tool, {"kind": "task", "task": t})

    boot = cfg.get("bootstrap") or {}
    if isinstance(boot, dict):
        btool = boot.get("tool")
        if btool and btool not in reserved:
            out.setdefault(btool, {"kind": "bootstrap"})

    corr = cfg.get("correction_tool")
    if corr and corr not in reserved:
        out.setdefault(corr, {"kind": "correction"})

    # Mid-flow intent switch tool — a real, schema-exposed reference an author can
    # emit; it MUST be generated/shipped or the deployed agent breaks on it.
    ic = cfg.get("intent_change") or {}
    if isinstance(ic, dict):
        itool = ic.get("tool")
        if itool and itool not in reserved:
            out.setdefault(itool, {"kind": "intent_change"})

    # The two control blocks this walk used to miss. A custom cancel/escalate tool
    # is as real a reference as any other: the push gate always rejected the bundle
    # when it was absent, while codegen never built it and the stub check never saw
    # it. Same treatment as the rest now.
    for block, kind in (("cancel", "cancel"), ("escalate", "escalate")):
        b = cfg.get(block) or {}
        if isinstance(b, dict):
            btool = b.get("tool")
            if btool and btool not in reserved:
                out.setdefault(btool, {"kind": kind})

    # on_exhaust.then.tool handlers (per-slot validation, steer_back, per-task
    # on_failure) — also real tool references that need a generated implementation.
    for s in cfg.get("slots", []) or []:
        if not isinstance(s, dict):
            continue
        et = _exhaust_then_tool(s.get("validation"))
        if et and et not in reserved:
            out.setdefault(et, {"kind": "exhaust", "slot": s})
    sb = _exhaust_then_tool(cfg.get("steer_back"))
    if sb and sb not in reserved:
        out.setdefault(sb, {"kind": "exhaust"})
    for t in cfg.get("tasks", []) or []:
        if not isinstance(t, dict):
            continue
        et = _exhaust_then_tool(t.get("on_failure"))
        if et and et not in reserved:
            out.setdefault(et, {"kind": "exhaust", "task": t})
        # An async task's timeout policy carries the SAME disposition shape — the
        # validator runs `_check_on_exhaust(awaits.on_timeout, …)` over it verbatim.
        awaits = t.get("awaits")
        if isinstance(awaits, dict):
            ot = _then_tool((awaits.get("on_timeout") or {}).get("then"))
            if ot and ot not in reserved:
                out.setdefault(ot, {"kind": "exhaust", "task": t})

    # The flow-level silence ladder's exhaust can fire a tool too (engine
    # `_no_input_fc = _resolve_exhaust_action(_exhaust, filled)`), and `no_input` is a
    # config-level key in its own right — not reachable from any slot/task walk above.
    ni = _exhaust_then_tool(cfg.get("no_input"))
    if ni and ni not in reserved:
        out.setdefault(ni, {"kind": "exhaust"})

    return out
